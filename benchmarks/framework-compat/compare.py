"""Compare each framework's results with the no-framework reference and write MATRIX.md.

    python benchmarks/framework-compat/compare.py
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["reference", "langchain_agent", "langgraph_graph", "crewai_crew", "autogen_agentchat",
         "openai_agents_sdk", "google_adk", "smolagents_agent"]


def load():
    out = {}
    for path in glob.glob(os.path.join(HERE, "results", "*.json")):
        if os.path.basename(path).startswith("multi_agent_"):
            continue
        d = json.load(open(path))
        out[d["framework"]] = d
    return out


def multi_agent_section():
    lines = ["## Multi-agent teams (multi_agent/run.py)", "",
             "Same `multi_agent_delegation` scenarios plus a legitimate-delegation control, run against teams built "
             "with each framework's own multi-agent mechanism. Calls are shown as tool (actor <- delegated_by).", ""]
    for path in sorted(glob.glob(os.path.join(HERE, "results", "multi_agent_*.json"))):
        d = json.load(open(path))
        ver = ", ".join("%s %s" % kv for kv in sorted(d["versions"].items()))
        lines += ["### %s (%s)" % (d["name"], ver), "", "| Mode | Scenario | Findings | Calls observed |",
                  "|---|---|---|---|"]
        for mode, rows in d["runs"].items():
            for sid, v in rows.items():
                calls = "; ".join("%s (%s%s)" % (c[0], c[1], " <- %s" % c[2] if c[2] else "") for c in v["calls"])
                lines.append("| %s | `%s` | %s | %s |" % (mode, sid, ", ".join(v["rules"]) or "none", calls or "none"))
        lines.append("")
    return lines


def main():
    res = load()
    ref = res["reference"]["runs"]
    lines = ["# Framework compatibility matrix", "",
             "Generated by `compare.py` from `results/*.json`. Same scripted brain, same AgentSec scenarios, "
             "same in-process ToolHost; only the agent framework differs. See README.md for what this does and "
             "does not show.", "",
             "| Framework | Versions | Vulnerable: scenarios with findings | Same findings as reference | "
             "Safe: findings (false positives) | Errors |", "|---|---|---|---|---|---|"]
    details = []
    for fw in [f for f in ORDER if f in res] + sorted(set(res) - set(ORDER)):
        d = res[fw]
        if "error" in d:
            lines.append("| %s | - | did not run: %s | - | - | - |" % (fw, d["error"][:80]))
            continue
        v, s = d["runs"]["vulnerable"]["scenarios"], d["runs"]["safe"]["scenarios"]
        same = [k for k in v if set(v[k]["rules"]) == set(ref["vulnerable"]["scenarios"][k]["rules"])]
        errs = sum(1 for x in list(v.values()) + list(s.values()) if x["status"] == "error")
        fp = sum(1 for x in s.values() if x["rules"])
        ver = ", ".join("%s %s" % kv for kv in sorted(d["versions"].items())) or "-"
        lines.append("| %s | %s | %d / %d | %d / %d | %d | %d |" % (
            d["name"], ver, sum(1 for x in v.values() if x["rules"]), len(v), len(same), len(v), fp, errs))
        diff = [k for k in v if k not in same]
        if diff and fw != "reference":
            details.append("### %s" % d["name"])
            details.append("")
            details.append("| Scenario | Reference findings | This framework | Calls observed |")
            details.append("|---|---|---|---|")
            for k in diff:
                details.append("| `%s` | %s | %s | %s |" % (
                    k, ", ".join(ref["vulnerable"]["scenarios"][k]["rules"]) or "none",
                    ", ".join(v[k]["rules"]) or "none" + (" (error: %s)" % v[k]["error"] if v[k]["error"] else ""),
                    ", ".join(v[k]["calls"]) or "none"))
            details.append("")
    lines += ["", "## Differences from the reference (vulnerable runs)", ""] + (details or ["None."])
    lines += [""] + multi_agent_section()
    path = os.path.join(HERE, "MATRIX.md")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
